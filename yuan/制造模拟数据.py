def 读写json数据(json_file, datas={}, model=0):
    '''
    @Time    :   2024/05/22 13:43:44
    @功能    :   读/写json文件
        model: 
            0:读取数据；1:追加写入数据；2:修改数据；3:覆写数据
       datas 结构{"a":{"aa":"bb"}}
    '''
    import json
    # 读取JSON文件
    def read_json():
        try:
            with open(json_file, 'r', encoding="utf-8") as file:
                data = json.load(file)
        except: data = {}
        return data
    # 写入JSON文件
    def write_json(json_data):
        with open(json_file, 'w', encoding='utf-8') as file:
            json.dump(json_data, file, ensure_ascii=False,indent=4)
    if model == 0:
        # 读取json数据
        return read_json()
    elif model == 1:
        # 追加写入json数据
        old_datas = read_json()
        write_json(old_datas+datas)
        return old_datas+datas
    elif model == 2:
        # 修改json数据; 返回原数据
        old_datas = read_json()
        write_json(datas)
        return old_datas
    elif model == 3:
        # 覆写json数据
        old_datas = read_json()
        write_json(datas)
        return old_datas
    else:
        print("操作excel的模式不对。请对照修改 0:读取数据；1:追加写入数据；2:修改数据；3:覆写数据(清空数据，重新写入)")
        return None
    

