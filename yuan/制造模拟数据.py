def 根据周岁计算出生日期(age):
    '''
    @Time    :   2024/11/06 16:38:44
    @功能    :   None
    '''
    # 获取当前日期
    当前日期 = datetime.now()
    # 计算出生日期
    出生日期 = 当前日期.replace(year=当前日期.year - age)
    print(出生日期.strftime("%Y-%m-%d"))
    return 出生日期.strftime("%Y-%m-%d")

def 根据虚岁计算出生日期(age):
    '''
    @Time    :   2024/11/06 16:39:31
    @功能    :   None
    '''
    # 获取当前日期
    当前日期 = datetime.now()

    # 假设某人的虚岁是25岁
    # 计算出生日期
    出生年份 = 当前日期.year - age + 1  # 虚岁需要加1
    出生日期 = 当前日期.replace(year=出生年份)
    print(出生日期.strftime("%Y-%m-%d"))
    return 出生日期.strftime("%Y-%m-%d")

def 根据出生日期计算周岁和虚岁(出生日期):
    '''
    @Time    :   2024/11/06 16:41:28
    @功能    :   None
    出生日期格式："2000-01-01"
    '''
    # 将字符串解析为 datetime 对象
    出生日期 = datetime.strptime(出生日期, "%Y-%m-%d")
    # 获取当前日期
    当前日期 = datetime.now()
    # 计算周岁
    周岁 = 当前日期.year - 出生日期.year - ((当前日期.month, 当前日期.day) < (出生日期.month, 出生日期.day))
    # 计算虚岁
    虚岁 = 周岁 + 1 if (当前日期.month, 当前日期.day) >= (出生日期.month, 出生日期.day) else 周岁
    print(f"周岁: {周岁}, 虚岁: {虚岁}")
    return {"周岁":周岁,"虚岁":虚岁}
